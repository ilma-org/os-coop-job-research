#!/usr/bin/env python3
"""Build the report cover page from a private member list, so nobody types it by hand.

  python3 scripts/make_cover.py                          # read .local/name.md, write report/cover.tex
  python3 scripts/make_cover.py --representative 1       # mark member 1 (line number) as the group representative
  python3 scripts/make_cover.py --sort id                # order by student ID only (default: section, then student ID)

The input is one line per member, in this order: first name, last name, mobile phone,
student ID, section. For example `Firstname Lastname 0XXXXXXXXX 6XXXXXXXXX Sec001`.
Keep the file in `.local/`, which is git-ignored. The output `report/cover.tex` is git-ignored too.

This script never prints a name, phone number or student ID, and neither of the two files may
be committed (AGENTS.md, hard rule 10). `report/main.tex` loads `cover.tex` only if it exists.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / ".local" / "name.md"
OUT = ROOT / "report" / "cover.tex"

TEX_SPECIAL = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
               "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}


def tex(text: str) -> str:
    return "".join(TEX_SPECIAL.get(ch, ch) for ch in text)


def read_members(path: Path) -> list[dict]:
    members = []
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip():
            continue
        parts = line.split()
        if len(parts) < 5:
            sys.exit(f"{path.name} line {number}: need first name, last name, phone, student ID and section")
        *names, phone, sid, section = parts
        if not re.fullmatch(r"0\d{9}", phone):
            sys.exit(f"{path.name} line {number}: the phone number must be 10 digits starting with 0")
        if not re.fullmatch(r"\d{9}", sid):
            sys.exit(f"{path.name} line {number}: the student ID must be 9 digits")
        found = re.fullmatch(r"(?i)sec(?:tion)?0*(\d)", section) or re.fullmatch(r"00(\d)", section)
        if not found or found.group(1) not in "12":
            sys.exit(f"{path.name} line {number}: the section must be Sec001 or Sec002")
        members.append({"name": " ".join(names), "phone": phone, "id": sid, "section": f"00{found.group(1)}", "line": len(members) + 1})
    if not 3 <= len(members) <= 5:
        sys.exit(f"the group must have 3 to 5 members, found {len(members)}")
    return members


SORTS = {
    "section-id": lambda m: (m["section"], m["id"]),
    "id": lambda m: m["id"],
    "file": lambda m: m["line"],
}


def cover_text(members: list[dict], representative: int | None) -> str:
    """`representative` is the member's line number in the input file, not the row number on the cover."""
    rows = []
    for n, m in enumerate(members, 1):
        name = tex(m["name"]) + (" (group representative)" if representative == m["line"] else "")
        rows.append(f"{n} & {m['id']} & {name} & {m['phone']} & {m['section']} \\\\")
    return (
        "% Generated by scripts/make_cover.py from .local/name.md. Holds student data: never commit this file.\n"
        "\\thispagestyle{empty}\n"
        "\\begin{center}\n"
        "\\vspace*{2.5cm}\n"
        "{\\LARGE\\bfseries GenAI-Assisted Career and Operating Systems Exploration}\\\\[0.6cm]\n"
        "{\\Large Site Reliability Engineer at Google}\\\\[2.2cm]\n"
        "{\\large\\bfseries Group members}\\\\[0.4cm]\n"
        "\\renewcommand{\\arraystretch}{1.35}\n"
        "\\begin{tabular}{@{}c l l l c@{}}\n"
        "\\hline\n"
        "No. & Student ID & Full name & Mobile phone & Section \\\\\n"
        "\\hline\n" + "\n".join(rows) + "\n\\hline\n"
        "\\end{tabular}\\\\[2cm]\n"
        "204341 Operating Systems\\\\\n"
        "Final Assignment\\\\[0.4cm]\n"
        "05 - 18 October 2026\n"
        "\\end{center}\n"
    )


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--source", type=Path, default=SRC, help="member list (default .local/name.md)")
    ap.add_argument("--representative", type=int, help="line number of the group representative")
    ap.add_argument("--sort", choices=sorted(SORTS), default="section-id",
                    help="order of the members on the cover (default: section, then student ID)")
    args = ap.parse_args()
    if not args.source.exists():
        sys.exit(f"{args.source} not found")
    members = read_members(args.source)
    if args.representative is not None and not 1 <= args.representative <= len(members):
        sys.exit(f"--representative must be between 1 and {len(members)}")
    members.sort(key=SORTS[args.sort])
    OUT.write_text(cover_text(members, args.representative), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} for {len(members)} members")
    return 0


if __name__ == "__main__":
    sys.exit(main())
