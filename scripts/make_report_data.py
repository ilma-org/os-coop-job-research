#!/usr/bin/env python3
"""Generate the data files the LaTeX report includes, so nobody types them by hand.

  python3 scripts/make_report_data.py              # write both files
  python3 scripts/make_report_data.py --check      # exit 1 if the files are out of date
  python3 scripts/make_report_data.py --include ai-checked   # also cite sources of ai-checked claims

Writes:
  report/references.bib           one entry per source URL in the claims, one per GenAI
                                  platform and model in the prompt logs, and the repo itself
  report/generated/genai-usage.tex  a table of the GenAI platforms and models used
  report/generated/counts.tex       LaTeX macros with log and claim counts (\\logsTotal and so on)
  report/generated/appendix.tex     the user prompts of every log marked significant, verbatim

By default only sources of `human-verified` claims are listed, because the report may only
rely on those. BibTeX prints just the entries the report cites, so the file may be longer
than the printed References. A URL that several claims cite gets the latest access date.
The three Google books and the pages of a few big documentation sites are each cited as one
reference (see GROUPS), with the chapters or pages read listed in the entry.
"""
from __future__ import annotations

import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path
from urllib.parse import urlparse

import kb_common as kb

BIB = kb.ROOT / "report" / "references.bib"
TABLE = kb.ROOT / "report" / "generated" / "genai-usage.tex"
COUNTS = kb.ROOT / "report" / "generated" / "counts.tex"
APPENDIX = kb.ROOT / "report" / "generated" / "appendix.tex"
HEADER = "% Generated by scripts/make_report_data.py from knowledge-base/ and prompts/. Do not edit by hand.\n"

STATUS_RANK = {"unverified": 0, "ai-checked": 1, "human-verified": 2}
VENDOR = {"claude code": "Anthropic", "codex": "OpenAI"}
ROLE_LABEL = {
    "research": "claim research",
    "author-check": "blind author check",
    "reviewer-recheck": "reviewer recheck",
    "drafting": "report drafting",
    "session-summary": "session summary",
}
ROLE_ORDER = list(ROLE_LABEL)

# Sources cited as one reference each: (key, URL prefix, title, what was read). The entry lists the
# chapters or pages read. Cite keys in report/sections/ use the group key, not one key per page.
GROUPS = [
    ("sre-book", "https://sre.google/sre-book/", "Site Reliability Engineering", "Chapters"),
    ("workbook", "https://sre.google/workbook/", "The Site Reliability Workbook", "Chapters"),
    ("bsrs", "https://google.github.io/building-secure-and-reliable-systems/raw/", "Building Secure and Reliable Systems", "Chapters"),
    ("man7", "https://man7.org/linux/man-pages/", "Linux man-pages", "Pages"),
    ("kernel-docs", "https://docs.kernel.org/", "The Linux Kernel documentation", "Pages"),
    ("kubernetes-docs", "https://kubernetes.io/docs/", "Kubernetes documentation", "Pages"),
    ("google-cloud-blog", "https://cloud.google.com/blog/", "Google Cloud Blog", "Posts"),
    ("sre-articles", "https://sre.google/resources/", "Google SRE website articles", "Articles"),
]

TEX_SPECIAL = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
               "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}


def tex(text: str) -> str:
    return "".join(TEX_SPECIAL.get(ch, ch) for ch in str(text))


def date_of(value) -> str:
    return value.isoformat() if hasattr(value, "isoformat") else str(value)


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def source_key(url: str) -> str:
    """A stable BibTeX key from the URL, for example sre-book-being-on-call."""
    u = urlparse(url)
    host = u.netloc.lower().removeprefix("www.")
    path = u.path.strip("/")
    if host == "sre.google":
        return slug(path) or "sre-google"
    if host == "google.github.io" and path.startswith("building-secure-and-reliable-systems"):
        return "bsrs-" + slug(path.removeprefix("building-secure-and-reliable-systems").removeprefix("/raw"))
    return slug(host.split(".")[0] if not path else f"{host.rsplit('.', 1)[0]}-{path}")


def collect_sources(min_status: str) -> dict[str, dict]:
    sources: dict[str, dict] = {}
    for topic in kb.topic_dirs():
        for note in kb.notes_in(topic):
            for claim in kb.claims_of(note):
                src = claim.get("source")
                if not src or STATUS_RANK.get(claim.get("status"), -1) < STATUS_RANK[min_status]:
                    continue
                url = src["url"]
                seen = sources.setdefault(url, {"title": src["title"], "kind": src.get("kind"),
                                                "accessed": date_of(src["accessed"]), "claims": []})
                seen["accessed"] = max(seen["accessed"], date_of(src["accessed"]))
                seen["claims"].append(claim["id"])
    return sources


def canonical_model(raw: str) -> str:
    """Normalize the model strings found in the prompt logs without guessing a version."""
    ids = sorted(set(re.findall(r"claude-(?:opus|sonnet|haiku|fable)-[0-9-]+|gpt-[\w.-]+", raw)))
    if ids and all(i.startswith("claude-") for i in ids) and len(ids) == 1:
        family, *ver = ids[0].removeprefix("claude-").split("-")
        return f"Claude {family.capitalize()} {'.'.join(ver)} ({ids[0]})"
    if ids and all(i.startswith("gpt-") for i in ids):
        return ", ".join(ids)
    names = re.findall(r"(Opus|Sonnet|Haiku|Fable) (\d+(?:\.\d+)*)", raw)
    if names:  # a session that switched models: list each model once
        return " and ".join(sorted({f"Claude {n} {v}" for n, v in names}))
    return raw.strip()


def collect_genai() -> dict[tuple[str, str], dict]:
    used: dict[tuple[str, str], dict] = {}
    for path in sorted((kb.ROOT / "prompts").glob("*.md")):
        _, data, _ = kb.load_note(path)
        if data.get("doc_type") != "prompt-log":
            continue
        platform = re.sub(r"\s*\(.*\)$", "", str(data["platform"])).strip()
        model = canonical_model(str(data["model"]))
        entry = used.setdefault((platform, model), {"roles": defaultdict(int), "dates": [], "logs": 0})
        entry["roles"][data.get("role", "research")] += 1
        entry["dates"].append(date_of(data["date"]))
        entry["logs"] += 1
    return used


def repo_url() -> str | None:
    url = kb.git("remote", "get-url", "origin", check=False).strip()
    match = re.match(r"(?:git@github\.com:|https://github\.com/)([\w.-]+/[\w.-]+?)(?:\.git)?$", url)
    return f"https://github.com/{match.group(1)}" if match else None


def used_for(roles: dict[str, int]) -> str:
    labels = [ROLE_LABEL.get(r, r) for r in ROLE_ORDER if r in roles]
    labels += [ROLE_LABEL.get(r, r) for r in roles if r not in ROLE_ORDER]
    return ", ".join(labels)


def group_of(url: str):
    return next((g for g in GROUPS if url.startswith(g[1])), None)


def group_entry(group, items: list[tuple[str, dict]]) -> str:
    key, base, title, noun = group
    slugs = sorted(url.removeprefix(base).strip("/").removesuffix(".html") for url, _ in items)
    dates = sorted(s["accessed"] for _, s in items)
    claims = sorted({c for _, s in items for c in s["claims"]})
    span = dates[0] if dates[0] == dates[-1] else f"{dates[0]} to {dates[-1]}"
    if noun == "Chapters":  # a whole book: give the count, the repository lists the chapter of every claim
        listing = f"{len(items)} chapters read at \\url{{{base}}}; the chapter of each claim is in the project repository"
    else:
        listing = f"{noun} read at \\url{{{base}}}: {tex(', '.join(slugs))}"
    return (f"@misc{{{key},\n  title   = {{{{{tex(title)}}}}},\n"
            f"  howpublished = {{{listing}}},\n"
            f"  note    = {{Accessed: {span}}},\n  annotation = {{claims {', '.join(claims)}}},\n}}\n")


def bib_text(min_status: str) -> str:
    out = [HEADER]
    keys: dict[str, str] = {}
    sources = collect_sources(min_status)
    for group in GROUPS:
        items = [(u, s) for u, s in sources.items() if group_of(u) is group]
        if items:
            out.append(group_entry(group, items))
    for url, s in sorted(sources.items(), key=lambda kv: source_key(kv[0])):
        if group_of(url):
            continue
        key = source_key(url)
        if key in keys:
            sys.exit(f"duplicate BibTeX key {key}: {keys[key]} and {url}")
        keys[key] = url
        out.append(f"@misc{{{key},\n  title   = {{{{{tex(s['title'])}}}}},\n  howpublished = {{\\url{{{url}}}}},\n"
                   f"  note    = {{Accessed: {s['accessed']}}},\n  annotation = {{claims {', '.join(s['claims'])}}},\n}}\n")
    for (platform, model), info in sorted(collect_genai().items()):
        key = f"genai-{slug(platform)}-{slug(model.split('(')[-1].rstrip(')') if '(' in model else model)}"
        vendor = VENDOR.get(platform.lower(), platform)
        out.append(f"@misc{{{key},\n  author  = {{{{{tex(vendor)}}}}},\n  title   = {{{{{tex(platform)}, {tex(model)}}}}},\n"
                   f"  howpublished = {{GenAI platform. Used for {tex(used_for(info['roles']).lower())}}},\n"
                   f"  note    = {{Accessed: {max(info['dates'])}}},\n}}\n")
    url = repo_url()
    if url:
        out.append(f"@misc{{repo,\n  title   = {{{{Knowledge base and prompt logs for the SRE career and OS research}}}},\n"
                   f"  howpublished = {{\\url{{{url}}}}},\n  note    = {{Accessed: {kb.git('log', '-1', '--format=%cs').strip()}}},\n"
                   f"  annotation = {{Cite the submitted tag, for example submitted-2026-10-18}},\n}}\n")
    return "\n".join(out)


def table_text() -> str:
    rows = []
    for (platform, model), info in sorted(collect_genai().items(), key=lambda kv: (kv[0][0], kv[0][1])):
        first, last = min(info["dates"]), max(info["dates"])
        period = first if first == last else f"{first} to {last}"
        rows.append(f"{tex(platform)}, {tex(model)} & {tex(used_for(info['roles']))} & {info['logs']} & {period} \\\\")
    return (HEADER + "\\begin{tabular}{@{}>{\\raggedright\\arraybackslash}p{0.34\\linewidth}>{\\raggedright\\arraybackslash}p{0.30\\linewidth}r>{\\raggedright\\arraybackslash}p{0.20\\linewidth}@{}}\n\\hline\n"
            "Platform and model & Used for & Logs & Period \\\\\n\\hline\n" + "\n".join(rows) + "\n\\hline\n\\end{tabular}\n")


def counts_text() -> str:
    claims = [c for topic in kb.topic_dirs() for note in kb.notes_in(topic) for c in kb.claims_of(note)]
    logs = [kb.load_note(p)[1] for p in sorted((kb.ROOT / "prompts").glob("*.md"))]
    logs = [d for d in logs if d.get("doc_type") == "prompt-log"]
    macros = {
        "logsTotal": len(logs),
        "logsSignificant": sum(1 for d in logs if d.get("significant")),
        "claimsTotal": len(claims),
        "claimsHumanVerified": sum(1 for c in claims if c["status"] == "human-verified"),
        "claimsAiChecked": sum(1 for c in claims if c["status"] == "ai-checked"),
        "claimsAssumption": sum(1 for c in claims if c["type"] == "assumption"),
        "sourcesTotal": len(collect_sources("unverified")),
    }
    return HEADER + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in macros.items())


THAI = re.compile(r"[\u0e00-\u0e7f](?:[\u0e00-\u0e7f ]*[\u0e00-\u0e7f])?")
PHASES = (("exploration", "Knowledge exploration"), ("report", "Report creation"))


def breakable(text: str) -> str:
    """Escape for LaTeX and allow a line break after a slash, so long paths and URLs do not overflow."""
    return tex(text).replace("/", "/\\allowbreak{}")


def prompt_tex(text: str) -> str:
    """One user prompt as LaTeX, with every word kept. Thai runs get the \\thai font command."""
    def line(s: str) -> str:
        out, pos = [], 0
        for m in THAI.finditer(s):
            out.append(breakable(s[pos:m.start()]) + "\\thai{" + m.group(0) + "}")
            pos = m.end()
        return "".join(out) + breakable(s[pos:])
    paragraphs = re.split(r"\n\s*\n", text.strip())
    return "\n\n".join(" \\\\{}\n".join(line(s.strip()) for s in p.split("\n")) for p in paragraphs)  # {} keeps a leading [ from being read as an option of \\


